const GUEST_ID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** A device's random guest id, or null when it is missing or not a UUID. */
function validGuestId(value) {
  return typeof value === 'string' && GUEST_ID_PATTERN.test(value) ? value.toLowerCase() : null;
}

/**
 * Returns a paginated list of photos, optionally filtered by location tag.
 *
 * Columns are listed rather than SELECT * so no guest ever receives another
 * device's guest_id — with one, they could unlike that device's likes or vote
 * for their own photos. Instead `liked` and `mine` are worked out here for the
 * device asking, from its X-Guest-Id header.
 */
async function handleListPhotos(request, env) {
  try {
    const url = new URL(request.url);
    const location = url.searchParams.get('location');
    const guestId = validGuestId(request.headers.get('X-Guest-Id'));

    const where = location ? 'WHERE p.location = ?3' : '';
    const binds = [guestId, guestId];
    if (location) binds.push(location);

    const results = await env.DB.prepare(`
      SELECT p.id, p.file_key, p.uploader_name, p.location, p.uploaded_at, p.is_favorite,
        COUNT(l.guest_id) AS like_count,
        MAX(l.created_at) AS last_liked_at,
        COALESCE(MAX(l.guest_id = ?1), 0) AS liked,
        COALESCE(p.guest_id = ?2, 0) AS mine
      FROM photos p
      LEFT JOIN likes l ON l.photo_id = p.id
      ${where}
      GROUP BY p.id
      ORDER BY p.uploaded_at DESC
    `).bind(...binds).all();

    // Ships the fingerprint alongside, so the client's baseline comes from the
    // same source as the value it will later compare against.
    const { version } = await galleryFingerprint(env);
    const featured_min_likes = await getFeaturedMinLikes(env);
    return json({ photos: results.results, version, featured_min_likes });

  } catch (err) {
    return json({ error: err.message }, 500);
  }
}

/**
 * Builds a cacheable image response, answering conditional requests with 304.
 * Carries the shared Cache-Control so caches.default will accept it; use
 * toPrivateCache() before handing it to the client.
 */
function imageResponse(body, contentType, etag, request) {
  if (etag && request.headers.get('If-None-Match') === etag) {
    return new Response(null, {
      status: 304,
      headers: { 'ETag': etag, 'Cache-Control': IMMUTABLE_SHARED }
    });
  }
  const headers = { 'Content-Type': contentType, 'Cache-Control': IMMUTABLE_SHARED };
  if (etag) headers['ETag'] = etag;
  return new Response(body, { headers });
}

/**
 * Downgrades a response to a private Cache-Control on its way to the browser.
 * caches.default refuses to store `private`, and these responses sit behind the
 * guest passphrase, so they are stored shared (the edge cache is only reachable
 * after the router's auth check) and marked private for everything downstream.
 */
function toPrivateCache(response) {
  const copy = new Response(response.body, response);
  copy.headers.set('Cache-Control', IMMUTABLE_PRIVATE);
  return copy;
}

/**
 * Serves a response from the edge cache, storing it on a miss.
 *
 * `build` may flag a response as too large to clone: cloning a streaming
 * response makes the runtime buffer whatever the slower branch hasn't read, and
 * originals run to 95MB against a 128MB memory limit. Those stream straight
 * through uncached; derivatives are small and always cache.
 */
async function withEdgeCache(request, ctx, build) {
  const cacheKey = new Request(new URL(request.url).toString(), { method: 'GET' });
  const cache = caches.default;

  const hit = await cache.match(cacheKey);
  if (hit) {
    const etag = hit.headers.get('ETag');
    if (etag && request.headers.get('If-None-Match') === etag) {
      return new Response(null, {
        status: 304,
        headers: { 'ETag': etag, 'Cache-Control': IMMUTABLE_PRIVATE }
      });
    }
    return toPrivateCache(hit);
  }

  const { response, cacheable = true } = await build();
  if (response.status === 200 && cacheable && ctx) {
    ctx.waitUntil(cache.put(cacheKey, response.clone()));
  }
  return toPrivateCache(response);
}

/** Streams a photo or thumbnail directly from R2 storage. */
async function handleGetImage(request, env, ctx, overrideKey) {
  const url = new URL(request.url);
  const fileKey = overrideKey || url.pathname.replace('/image/', '');
  if (!fileKey.startsWith('photos/') || fileKey.includes('..')) {
    return new Response('Not found', { status: 404 });
  }

  return withEdgeCache(request, ctx, async () => {
    const object = await env.BUCKET.get(fileKey);
    if (!object) {
      return { response: new Response('Not found', { status: 404 }) };
    }
    return {
      response: imageResponse(
        object.body,
        object.httpMetadata?.contentType || 'image/jpeg',
        object.httpEtag,
        request
      ),
      cacheable: object.size <= MAX_CACHEABLE_BYTES
    };
  });
}

/**
 * Serves a stored display derivative, generating and storing it on a miss.
 *
 * Path is /v/{variant}/{originalKey}, e.g. /v/grid/photos/1738-abc.jpg, so
 * both the derivative key and its source are known without a D1 lookup.
 */
async function handleGetVariant(request, env, ctx) {
  const url = new URL(request.url);
  const rest = decodeURIComponent(url.pathname.slice('/v/'.length));
  const split = rest.indexOf('/');
  if (split === -1) return new Response('Not found', { status: 404 });

  const variantName = rest.slice(0, split);
  const originalKey = rest.slice(split + 1);
  const spec = VARIANTS[variantName];

  if (!spec || !originalKey.startsWith('photos/') || originalKey.includes('..')) {
    return new Response('Not found', { status: 404 });
  }

  const key = derivedKey(originalKey, variantName);
  let fallbackToOriginal = false;

  const response = await withEdgeCache(request, ctx, async () => {
    const stored = await env.BUCKET.get(key);
    if (stored) {
      return { response: imageResponse(stored.body, spec.format, stored.httpEtag, request) };
    }

    const generated = await generateVariant(env, originalKey, variantName);
    if (!generated.ok) {
      fallbackToOriginal = true;
      return { response: new Response('Not transformable', { status: 415 }) };
    }
    return { response: imageResponse(generated.body, spec.format, generated.etag, request) };
  });

  // Too large for the Images binding, or a format it can't decode. Serving the
  // original keeps the photo visible rather than showing a broken tile.
  //
  // This caches the original's bytes under the /v/ URL, which is intended: the
  // decision turns only on the source's size and content type, and R2 objects
  // here are never overwritten, so the fallback is stable for a given key.
  if (fallbackToOriginal) {
    return handleGetImage(request, env, ctx, originalKey);
  }
  return response;
}

// Retries back off rather than firing on the default short delay. Failures
// arrive in bursts — twenty photos landing together — and an immediate retry
// lands inside the same congestion that caused it. Backing off past the burst
// is the difference between a retry that can succeed and one that cannot.
//
// The first schedule (30s/60s/120s) was tuned against a single burst and was
// still too short: three back-to-back batches of 20 produce 120 messages, and
// at max_batch_size 1 the queue is still draining its own backlog minutes
// later, so the retries landed inside that rather than after it.
const RETRY_BASE_DELAY_SECONDS = 120;
const RETRY_MAX_DELAY_SECONDS = 600;

/** 2min, 4min, then 8min — long enough to outlast the queue's own backlog. */
function retryDelaySeconds(attempt) {
  return Math.min(RETRY_BASE_DELAY_SECONDS * 2 ** (attempt - 1), RETRY_MAX_DELAY_SECONDS);
}

/** True when a derivative is already stored, so a retry can skip rebuilding it. */
async function variantExists(env, originalKey, variantName) {
  return (await env.BUCKET.head(derivedKey(originalKey, variantName))) !== null;
}

/** derived/{id}/{variant}.{ext} — the id is shared with the original photos/ key. */
function derivedKey(originalKey, variantName) {
  const base = originalKey.slice('photos/'.length).replace(/\.[^.]+$/, '');
  return `derived/${base}/${variantName}.${VARIANTS[variantName].ext}`;
}

/**
 * Transforms an original into one stored derivative via the Images binding.
 *
 * Returns a discriminated result rather than a bare null, because the two
 * failure modes need opposite handling. A source over the binding's size cap,
 * or one it cannot decode, will never transform however often it is tried —
 * callers fall back to the original and the queue acks. A transform that
 * throws is usually transient (contention while a batch of uploads lands), so
 * the queue must retry it or the derivative is never built at all.
 *
 * Derivatives are small (20-350KB), so buffering is cheaper than tee-ing the
 * stream and safer than a fire-and-forget write that could be cancelled.
 */
async function generateVariant(env, originalKey, variantName) {
  const spec = VARIANTS[variantName];
  if (!spec) return { ok: false, retryable: false };

  const original = await env.BUCKET.get(originalKey);
  if (!original) return { ok: false, retryable: false };

  const contentType = original.httpMetadata?.contentType || '';
  if (original.size > MAX_TRANSFORM_BYTES || UNDECODABLE_TYPES.has(contentType)) {
    return { ok: false, retryable: false };
  }

  try {
    const result = await env.IMAGES
      .input(original.body)
      .transform({ width: spec.width, height: spec.width, fit: 'scale-down' })
      .output({ format: spec.format, quality: spec.quality });

    const body = await result.response().arrayBuffer();
    const written = await env.BUCKET.put(derivedKey(originalKey, variantName), body, {
      httpMetadata: { contentType: spec.format, cacheControl: IMMUTABLE_SHARED }
    });
    return { ok: true, body, etag: written?.httpEtag };
  } catch (err) {
    console.error('transform failed', originalKey, variantName, err);
    return { ok: false, retryable: true };
  }
}

/**
 * Sets or clears this device's like on a photo.
 *
 * Takes the desired state rather than toggling, so a double tap or a retried
 * request lands on the same answer instead of flipping it back. The primary
 * key on (photo_id, guest_id) is what guarantees one like per device.
 */
async function handleLike(request, env) {
  try {
    const ip = request.headers.get('CF-Connecting-IP') ?? 'unknown';
    if (!await checkRateLimit(env.RATE_LIMIT_KV, ip, 'like', 120)) {
      return json({ error: 'Too many likes. Try again in a minute.' }, 429);
    }

    const { photo_id, liked, guest_id, name } = await request.json();
    const guestId = validGuestId(guest_id);
    const guestName = typeof name === 'string' ? name.trim() : '';
    if (!guestId) return json({ error: 'Invalid guest id' }, 400);
    if (!guestName) return json({ error: 'Name is required' }, 400);
    if (guestName.length > 100) return json({ error: 'Name is too long' }, 400);
    if (!Number.isInteger(photo_id) || typeof liked !== 'boolean') {
      return json({ error: 'photo_id and liked are required' }, 400);
    }

    const photo = await env.DB.prepare('SELECT guest_id FROM photos WHERE id = ?')
      .bind(photo_id).first();
    if (!photo) return json({ error: 'Photo not found' }, 404);
    if (photo.guest_id && photo.guest_id === guestId) {
      return json({ error: 'own_photo' }, 403);
    }

    if (liked) {
      await env.DB.prepare(
        'INSERT OR IGNORE INTO likes (photo_id, guest_id, guest_name) VALUES (?, ?, ?)'
      ).bind(photo_id, guestId, guestName).run();
    } else {
      await env.DB.prepare('DELETE FROM likes WHERE photo_id = ? AND guest_id = ?')
        .bind(photo_id, guestId).run();
    }

    const { like_count } = await env.DB.prepare(
      'SELECT COUNT(*) AS like_count FROM likes WHERE photo_id = ?'
    ).bind(photo_id).first();
    return json({ liked, like_count });
  } catch (err) {
    return json({ error: err.message }, 500);
  }
}

