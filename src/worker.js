/**
 * Settings → Theme shows each theme as a thumbnail of the guest home page,
 * framed by the admin page. This is the only path any page may frame, and only
 * a page on this same site.
 */
const THEME_PREVIEW_PATH = '/admin/theme-preview';

/**
 * Clones a response and applies every SECURITY_HEADERS entry to the copy.
 * sameOriginFrame relaxes "never framed" to "framed only by this site".
 */
function addSecurityHeaders(response, { sameOriginFrame = false } = {}) {
  const newHeaders = new Headers(response.headers);
  Object.entries(SECURITY_HEADERS).forEach(([k, v]) => newHeaders.set(k, v));
  if (sameOriginFrame) {
    newHeaders.set('X-Frame-Options', 'SAMEORIGIN');
    newHeaders.set('Content-Security-Policy',
      SECURITY_HEADERS['Content-Security-Policy'].replace("frame-ancestors 'none'", "frame-ancestors 'self'"));
  }
  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers: newHeaders
  });
}

// ─── Entry Point ──────────────────────────────────────────────────────────────

export default {
  /** Wraps every response with security headers before returning it to the client. */
  async fetch(request, env, ctx) {
    const response = await handleRequest(request, env, ctx);
    return addSecurityHeaders(response, {
      sameOriginFrame: new URL(request.url).pathname === THEME_PREVIEW_PATH,
    });
  },

  /**
   * Generates display derivatives for freshly uploaded photos so the first
   * guest to open the gallery doesn't pay the transformation latency.
   * The /v/ route regenerates anything this misses, so a permanently failed
   * message costs nothing but a slower first view.
   */
  async queue(batch, env) {
    for (const message of batch.messages) {
      try {
        const { fileKey, variant: requestedVariant } = message.body;
        const attempt = message.attempts ?? 1;

        // One variant per message. Both transforms in a single invocation
        // exceeded the CPU limit — the runtime killed the job partway, which
        // is why `grid` always survived and `display` never did: `display`
        // runs second and wore the overrun every time. Splitting them gives
        // each transform its own invocation and its own budget.
        //
        // Messages enqueued before the split carry no variant and still mean
        // the whole set; they drain within one retry cycle.
        const variants = requestedVariant ? [requestedVariant] : Object.keys(VARIANTS);

        // generateVariant reports failure in its return value rather than
        // throwing, so that value is the only signal there is. Acking
        // regardless left every transient failure permanently unbuilt: the
        // message was marked done on the first attempt and max_retries never
        // engaged. Guests then paid an inline transform on first view.
        //
        // Only retryable failures come back here — an unsupported source is
        // reported as permanent and acked, since retrying cannot change it.
        const failed = [];
        for (const variant of variants) {
          // Skip whatever already landed on an earlier attempt. Variants are
          // built in order and the later, larger one is the one that fails, so
          // rebuilding the earlier one first spends exactly the budget that
          // starved it — a naive retry replays the losing order and fails the
          // same way. Only checked on retries: on the first attempt nothing
          // exists yet and the lookup would be two wasted operations a photo.
          if (attempt > 1 && await variantExists(env, fileKey, variant)) continue;

          const result = await generateVariant(env, fileKey, variant);
          if (!result.ok && result.retryable) failed.push(variant);
        }

        if (failed.length > 0) {
          console.error('derivative variants failed', fileKey, failed.join(','), 'attempt', attempt);
          message.retry({ delaySeconds: retryDelaySeconds(attempt) });
        } else {
          message.ack();
        }
      } catch (err) {
        console.error('derivative job failed', message.body, err);
        message.retry({ delaySeconds: retryDelaySeconds(message.attempts ?? 1) });
      }
    }
  },

  /**
   * Repairs derivatives the queue gave up on.
   *
   * Roughly 3% of transforms fail under burst load, and occasionally all three
   * retries fail too — at which point the queue is finished and the gap only
   * closes when a guest happens to open that exact photo, paying for the
   * rebuild themselves. `grid` heals quickly because every gallery load
   * requests every tile; `display` is only fetched when someone opens that one
   * photo, so those gaps can sit indefinitely.
   *
   * This closes them on a schedule instead, so the cost lands here rather than
   * on a guest on cellular. Gated on a flag that defaults to off: the cron
   * fires on Cloudflare's schedule regardless, and a sweep against a static
   * bucket is pure waste.
   */
  async scheduled(event, env, ctx) {
    if (!await getSweepEnabled(env)) return;

    try {
      const { missing } = await findMissingDerivatives(env);
      if (missing.length === 0) return;

      const { rebuilt, unsupported, failed } =
        await rebuildBatch(env, missing, SWEEP_LIMIT, SWEEP_MAX_EXAMINED);

      console.log('derivative sweep', JSON.stringify({
        missing: missing.length,
        rebuilt: rebuilt.length,
        unsupported: unsupported.length,
        failed: failed.length
      }));
    } catch (err) {
      console.error('derivative sweep failed', err);
    }
  }
};

// ─── Request Router ───────────────────────────────────────────────────────────

/** Dispatches every incoming request to the appropriate handler. */
async function handleRequest(request, env, ctx) {
  if (request.method === 'OPTIONS') {
    return new Response(null, { headers: CORS_HEADERS });
  }

  const url = new URL(request.url);

  // Emergency hard override — blocks everything including admin.
  if (env.MAINTENANCE_MODE === 'true') {
    return new Response(PRE_WEDDING_HTML, {
      status: 503,
      headers: { 'Content-Type': 'text/html; charset=utf-8', 'Retry-After': '3600' }
    });
  }

  // Also creates the database tables on a brand-new deployment.
  const requestConfig = await getRequestConfig(env);
  const siteMode = requestConfig.siteMode;
  // Every check below reads env.guestPassphrase and env.adminSecret, so
  // resolve them once here. The passphrase is empty until one is saved in
  // Settings, and then no guest can sign in; the admin secret is empty until
  // the owner creates a password, and then /admin offers only the setup form.
  env = withRequestConfig(env, requestConfig);
  const isAdminRoute = url.pathname === '/admin' || url.pathname === '/admin/login'
    || url.pathname === '/admin/setup';
  const hasAdminSession = await isAdminAuthed(request, env);

  if (!isAdminRoute && !hasAdminSession) {
    if (siteMode === 'pre') {
      return new Response(PRE_WEDDING_HTML, {
        headers: { 'Content-Type': 'text/html; charset=utf-8' }
      });
    }
    if (siteMode === 'post' && !await isAuthed(request, env)) {
      return new Response(renderPage(POST_WEDDING_HTML, await getPageConfig(env)), {
        headers: { 'Content-Type': 'text/html; charset=utf-8' }
      });
    }
  }

  if (url.pathname === '/' && request.method === 'GET') {
    const cookie = request.headers.get('Cookie') || '';
    const hasAuth = await anyVerifies(
      getCookieValues(cookie, 'auth'), verifySessionToken, env.guestPassphrase
    );
    // Not case-sensitive, like the password page: passphrases are stored
    // lowercase, so ?p=Sunflower from a hand-typed link still signs in.
    const param = (url.searchParams.get('p') || '').trim().toLowerCase();

    if (env.guestPassphrase && param === env.guestPassphrase) {
      const sessionToken = await generateSessionToken(env.guestPassphrase);
      return new Response(null, {
        status: 302,
        headers: {
          'Location': '/',
          'Set-Cookie': `auth=${sessionToken}; ${SESSION_COOKIE_ATTRS}`
        }
      });
    }

    if (hasAuth) {
      // Re-issue the cookie on every authenticated load, so a guest who keeps
      // coming back never hits the year's expiry. The token value is
      // unchanged, so this signs nobody in or out.
      const refreshed = await generateSessionToken(env.guestPassphrase);
      return new Response(renderPage(HTML, await getPageConfig(env)), {
        headers: {
          'Content-Type': 'text/html; charset=utf-8',
          'Set-Cookie': `auth=${refreshed}; ${SESSION_COOKIE_ATTRS}`
        }
      });
    }

    return new Response(renderPage(GATE_HTML, await getPageConfig(env)), {
      headers: { 'Content-Type': 'text/html; charset=utf-8' }
    });
  }

  // Disallow all crawlers and AI training bots by name; wildcard alone isn't
  // enough because some scrapers ignore the catch-all and only respect named rules.
  if (url.pathname === '/robots.txt' && request.method === 'GET') {
    return new Response(
      'User-agent: *\nDisallow: /\n\nUser-agent: GPTBot\nDisallow: /\n\nUser-agent: ClaudeBot\nDisallow: /\n\nUser-agent: CCBot\nDisallow: /',
      { headers: { 'Content-Type': 'text/plain' } }
    );
  }

  if (url.pathname === '/auth' && request.method === 'POST') {
    return handleAuth(request, env);
  }

  if (url.pathname === '/admin' && request.method === 'GET') {
    if (!hasAdminSession) {
      // A brand-new deployment has no admin password yet: the first visitor
      // creates one. See handleAdminSetup.
      const page = env.adminSecret ? ADMIN_GATE_HTML : ADMIN_SETUP_HTML;
      return new Response(renderPage(page, await getPageConfig(env)), {
        headers: { 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'no-store' }
      });
    }
    // Same refresh as the guest cookie above.
    const refreshedAdmin = await generateAdminToken(env.adminSecret);
    return new Response(renderPage(ADMIN_HTML, await getPageConfig(env)), {
      headers: {
        'Content-Type': 'text/html; charset=utf-8',
        'Set-Cookie': `admin_auth=${refreshedAdmin}; ${ADMIN_COOKIE_ATTRS}`
      }
    });
  }

  if (url.pathname === THEME_PREVIEW_PATH && request.method === 'GET') {
    return handleThemePreview(url, env, hasAdminSession);
  }

  if (url.pathname === '/admin/login' && request.method === 'POST') {
    return handleAdminLogin(request, env);
  }

  if (url.pathname === '/admin/setup' && request.method === 'POST') {
    return handleAdminSetup(request, env);
  }

  if (url.pathname === '/admin/password' && request.method === 'GET') {
    if (!hasAdminSession) return new Response('Unauthorized', { status: 401 });
    return json({ managedByCloudflare: Boolean(env.ADMIN_PASSWORD) });
  }

  if (url.pathname === '/admin/password' && request.method === 'POST') {
    if (!hasAdminSession) return new Response('Unauthorized', { status: 401 });
    return handleChangeAdminPassword(request, env);
  }

  if (url.pathname === '/favorite' && request.method === 'POST') {
    if (!hasAdminSession) {
      return new Response('Unauthorized', { status: 401 });
    }
    return handleFavorite(request, env);
  }

  if (url.pathname === '/like' && request.method === 'POST') {
    if (!await isAuthed(request, env)) return new Response('Unauthorized', { status: 401 });
    return handleLike(request, env);
  }

  if (url.pathname === '/delete' && request.method === 'POST') {
    if (!hasAdminSession) {
      return new Response('Not found', { status: 404 });
    }
    return handleDelete(request, env);
  }

  if (url.pathname === '/rename' && request.method === 'POST') {
    if (!hasAdminSession) {
      return new Response('Not found', { status: 404 });
    }
    return handleRename(request, env);
  }

  if (url.pathname === '/upload' && request.method === 'POST') {
    return handleUpload(request, env, ctx);
  }

  if (url.pathname === '/leaderboard' && request.method === 'GET') {
    if (!await isAuthed(request, env)) {
      return new Response('Unauthorized', { status: 401 });
    }
    return handleLeaderboard(request, env);
  }

  if (url.pathname === '/rankings' && request.method === 'GET') {
    if (!await isAuthed(request, env)) {
      return new Response('Unauthorized', { status: 401 });
    }
    return handleRankings(request, env);
  }

  if (url.pathname === '/photo-count' && request.method === 'GET') {
    if (!await isAuthed(request, env)) {
      return new Response('Unauthorized', { status: 401 });
    }
    return handlePhotoCount(request, env);
  }

  if (url.pathname === '/photos' && request.method === 'GET') {
    if (!await isAuthed(request, env)) return new Response('Unauthorized', { status: 401 });
    return handleListPhotos(request, env);
  }

  if (url.pathname === '/storage' && request.method === 'GET') {
    if (!hasAdminSession) {
      return new Response('Unauthorized', { status: 401 });
    }
    return handleStorage(request, env);
  }

  if (url.pathname === '/presign' && request.method === 'GET') {
    if (!hasAdminSession) {
      return new Response('Unauthorized', { status: 401 });
    }
    return handlePresign(request, env);
  }

  if (url.pathname === '/derivatives' && (request.method === 'GET' || request.method === 'POST')) {
    if (!hasAdminSession) {
      return new Response('Unauthorized', { status: 401 });
    }
    return handleDerivatives(request, env);
  }

  if (url.pathname.startsWith('/image/') && request.method === 'GET') {
    if (!await isAuthed(request, env)) return new Response('Unauthorized', { status: 401 });
    return handleGetImage(request, env, ctx);
  }

  if (url.pathname.startsWith('/v/') && request.method === 'GET') {
    if (!await isAuthed(request, env)) return new Response('Unauthorized', { status: 401 });
    return handleGetVariant(request, env, ctx);
  }

  if (url.pathname === '/sweep' && request.method === 'GET') {
    if (!hasAdminSession) return new Response('Unauthorized', { status: 401 });
    return handleGetSweep(request, env);
  }

  if (url.pathname === '/sweep' && request.method === 'POST') {
    if (!hasAdminSession) return new Response('Unauthorized', { status: 401 });
    return handleSetSweep(request, env);
  }

  if (url.pathname === '/featured-min' && request.method === 'POST') {
    if (!hasAdminSession) return new Response('Unauthorized', { status: 401 });
    return handleSetFeaturedMin(request, env);
  }

  if (url.pathname === '/couple-names' && request.method === 'GET') {
    if (!hasAdminSession) return new Response('Unauthorized', { status: 401 });
    return json(await getCoupleNames(env));
  }

  if (url.pathname === '/couple-names' && request.method === 'POST') {
    if (!hasAdminSession) return new Response('Unauthorized', { status: 401 });
    return handleSetCoupleNames(request, env);
  }

  if (url.pathname === '/guest-passphrase' && request.method === 'GET') {
    if (!hasAdminSession) return new Response('Unauthorized', { status: 401 });
    return handleGetGuestPassphrase(request, env);
  }

  if (url.pathname === '/guest-passphrase' && request.method === 'POST') {
    if (!hasAdminSession) return new Response('Unauthorized', { status: 401 });
    return handleSetGuestPassphrase(request, env);
  }

  if (url.pathname === '/stats-timezone' && request.method === 'POST') {
    if (!hasAdminSession) return new Response('Unauthorized', { status: 401 });
    return handleSetStatsTimezone(request, env);
  }

  if (url.pathname === '/theme' && request.method === 'POST') {
    if (!hasAdminSession) return new Response('Unauthorized', { status: 401 });
    return handleSetTheme(request, env);
  }

  if (url.pathname === '/locations' && request.method === 'POST') {
    if (!hasAdminSession) return new Response('Unauthorized', { status: 401 });
    return handleSetLocations(request, env);
  }

  if (url.pathname === '/site-mode' && request.method === 'GET') {
    if (!hasAdminSession) return new Response('Unauthorized', { status: 401 });
    return handleGetSiteMode(request, env);
  }

  if (url.pathname === '/site-mode' && request.method === 'POST') {
    if (!hasAdminSession) return new Response('Unauthorized', { status: 401 });
    return handleSetSiteMode(request, env);
  }

  return new Response('Not found', { status: 404 });
}

// ─── Database setup ───────────────────────────────────────────────────────────

/**
 * The database creates itself. A fresh deployment has an empty D1 database, so
 * the first request runs SCHEMA_STATEMENTS and records SCHEMA_VERSION in
 * config; nobody has to run a migration by hand.
 *
 * To change the schema later:
 *   1. Update SCHEMA_STATEMENTS to the new shape (it is what new deployments get).
 *   2. Bump SCHEMA_VERSION.
 *   3. Add SCHEMA_UPGRADES[newVersion]: the statements that take an existing
 *      database from the previous version to this one.
 * Existing deployments pick the upgrade up on their next request after deploying.
 */
const SCHEMA_VERSION = 1;

const SCHEMA_STATEMENTS = [
  // Display sizes are derived from file_key by convention
  // (derived/{id}/{variant}), so no derivative keys are stored here.
  `CREATE TABLE IF NOT EXISTS photos (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    file_key TEXT NOT NULL,
    uploader_name TEXT,
    location TEXT,
    uploaded_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    is_favorite INTEGER NOT NULL DEFAULT 0,
    guest_id TEXT
  )`,
  // One like per photo per device: the primary key makes a repeat a no-op.
  `CREATE TABLE IF NOT EXISTS likes (
    photo_id   INTEGER NOT NULL,
    guest_id   TEXT NOT NULL,
    guest_name TEXT NOT NULL,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (photo_id, guest_id)
  )`,
  `CREATE TABLE IF NOT EXISTS config (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
  )`,
];

/** { version: [statements] } — each takes a database from version - 1 to version. */
const SCHEMA_UPGRADES = {};

/**
 * Brings the database up to SCHEMA_VERSION in one transaction, so a failure
 * leaves it as it was. `from` is the version it is at: 0 for an empty database,
 * which gets the full current schema rather than replaying every upgrade.
 * Safe for two requests to run at once: the statements are idempotent.
 */
async function ensureSchema(db, from) {
  const statements = from === 0
    ? SCHEMA_STATEMENTS
    : Object.keys(SCHEMA_UPGRADES)
        .map(Number).filter(v => v > from && v <= SCHEMA_VERSION).sort((a, b) => a - b)
        .flatMap(v => SCHEMA_UPGRADES[v]);
  await db.batch([
    ...statements.map(sql => db.prepare(sql)),
    db.prepare(
      'INSERT INTO config (key, value) VALUES (?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value'
    ).bind('schema_version', String(SCHEMA_VERSION)),
  ]);
}

// ─── Site Mode ────────────────────────────────────────────────────────────────

/**
 * The config every request needs, in one D1 read: the site mode, the guest
 * passphrase, the stored admin password hash and the schema version. Every
 * photo tile is a request that checks sign-in, so these must not cost a read each.
 *
 * Reading the schema version here is what lets the database set itself up for
 * free: a missing config table (a brand-new deployment) or an old version runs
 * ensureSchema, then reads again.
 *
 * The passphrase lives only in Settings (D1). Until one is saved it is empty,
 * and an empty passphrase signs nobody in — see verifySessionToken. If D1 is
 * unreachable the site mode falls back to live, but the passphrase and admin
 * hash fall back to empty: there is no second copy to fall back to, and failing
 * closed beats guessing.
 */
async function getRequestConfig(env) {
  const read = async () => {
    const { results } = await env.DB.prepare(
      'SELECT key, value FROM config WHERE key IN (?, ?, ?, ?)'
    ).bind('site_mode', 'guest_passphrase', 'admin_password_hash', 'schema_version').all();
    return Object.fromEntries((results || []).map(r => [r.key, r.value]));
  };
  try {
    let byKey;
    try {
      byKey = await read();
    } catch (err) {
      // Only a missing table means "new database". Any other failure is an
      // outage, and treating it as version 0 would mark an old database as
      // current without running its upgrades.
      if (!/no such table/i.test(String(err?.message))) throw err;
      byKey = null;
    }
    const version = Number(byKey?.schema_version || 0);
    if (!byKey || version < SCHEMA_VERSION) {
      await ensureSchema(env.DB, version);
      byKey = await read();
    }
    return {
      siteMode: byKey.site_mode || 'live',
      guestPassphrase: byKey.guest_passphrase || '',
      adminPasswordHash: byKey.admin_password_hash || '',
    };
  } catch {
    return { siteMode: 'live', guestPassphrase: '', adminPasswordHash: '' };
  }
}

