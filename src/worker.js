/**
 * Sets the uploader name on a set of photos, for merging the two names a guest
 * ends up with after typing theirs differently on two devices.
 *
 * Only the photos sent are changed. The guest's devices keep whatever name they
 * have stored, so later uploads can still arrive under the old spelling.
 */
async function handleRename(request, env) {
  try {
    const { ids, name } = await request.json();
    const newName = typeof name === 'string' ? name.trim() : '';
    if (!newName) return json({ error: 'Name is required' }, 400);
    if (newName.length > 100) return json({ error: 'Name is too long' }, 400);
    if (!Array.isArray(ids) || ids.length === 0 || !ids.every(Number.isInteger)) {
      return json({ error: 'ids must be a non-empty list of photo ids' }, 400);
    }

    // D1 caps bound parameters per statement, so large selections are split
    // into chunks and sent together as one batch.
    const CHUNK = 90;
    const statements = [];
    for (let i = 0; i < ids.length; i += CHUNK) {
      const chunk = ids.slice(i, i + CHUNK);
      statements.push(env.DB.prepare(
        `UPDATE photos SET uploader_name = ? WHERE id IN (${chunk.map(() => '?').join(',')})`
      ).bind(newName, ...chunk));
    }
    const results = await env.DB.batch(statements);
    const renamed = results.reduce((sum, r) => sum + (r.meta?.changes ?? 0), 0);

    return json({ success: true, renamed, name: newName });
  } catch (err) {
    return json({ error: err.message }, 500);
  }
}

