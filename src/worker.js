/** Queries the photos table to return rank, total uploads, and top uploader context for the given name. */
async function handleLeaderboard(request, env) {
  try {
    const url = new URL(request.url);
    const name = url.searchParams.get('name');
    if (!name) return json({ error: 'Name required' }, 400);

    const results = await env.DB.prepare(`
      SELECT uploader_name, COUNT(*) as total
      FROM photos
      GROUP BY uploader_name
      ORDER BY total DESC
    `).all();

    const uploaders = results.results;
    const total_uploaders = uploaders.length;
    const guest = uploaders.find(u => u.uploader_name === name);
    const guest_total = guest ? guest.total : 0;

    let rank = null;
    let tied = false;
    if (guest) {
      const higher = uploaders.filter(u => u.total > guest_total).length;
      const sameRank = uploaders.filter(u => u.total === guest_total).length;
      rank = higher + 1;
      tied = sameRank > 1;
    }

    const first = uploaders[0] || null;
    const second = uploaders[1] || null;

    return json({
      name,
      guest_total,
      rank,
      tied,
      total_uploaders,
      first_place_name: first?.uploader_name || null,
      first_place_total: first?.total || 0,
      second_place_name: second?.uploader_name || null,
      second_place_total: second?.total || 0,
    });
  } catch (err) {
    return json({ error: err.message }, 500);
  }
}

/** Returns the total photo count — used by the client to detect new uploads without re-fetching the full list. */
/**
 * Cheap fingerprint of the whole gallery, for clients deciding whether to refetch.
 *
 * A count alone misses two things that change what a guest should be seeing:
 * an admin starring a photo (count unchanged) and a delete paired with an upload
 * (count unchanged). max_id catches new photos, favorites catches starring, and
 * count catches deletes.
 */
async function galleryFingerprint(env) {
  // Likes and the threshold decide what Featured holds, so a change to either
  // has to move the fingerprint too. A count alone misses one guest liking a
  // photo while another unlikes a different one; summing photo ids catches
  // which photos the likes sit on.
  const r = await env.DB.prepare(
    `SELECT COUNT(*) AS count, COALESCE(MAX(id), 0) AS max_id, COALESCE(SUM(is_favorite), 0) AS favorites,
       (SELECT COUNT(*) || '-' || COALESCE(SUM(photo_id), 0) FROM likes) AS likes
     FROM photos`
  ).first();
  const min = await getFeaturedMinLikes(env);
  return { count: r.count, version: `${r.count}.${r.max_id}.${r.favorites}.${r.likes}.${min}` };
}

async function handlePhotoCount(request, env) {
  try {
    return json(await galleryFingerprint(env));
  } catch (err) {
    return json({ error: err.message }, 500);
  }
}

