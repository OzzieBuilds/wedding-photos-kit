/**
 * Validates and stores an uploaded photo in R2, records metadata in D1, and
 * queues generation of its display derivatives.
 *
 * Only the original is uploaded — display sizes are produced server-side by
 * Cloudflare Images rather than on the guest's phone.
 */
async function handleUpload(request, env, ctx) {
  try {
    if (!await isAuthed(request, env)) return new Response('Unauthorized', { status: 401 });
    const ip = request.headers.get('CF-Connecting-IP') ?? 'unknown';
    if (!await checkRateLimit(env.RATE_LIMIT_KV, ip, 'upload', 100)) {
      return json({ error: 'Upload limit reached. Try again in a minute.' }, 429);
    }

    const formData = await request.formData();
    const file = formData.get('file');
    const uploaderName = formData.get('uploader_name') || 'Anonymous';
    const location = formData.get('location') || 'Untagged';
    const guestId = validGuestId(formData.get('guest_id'));

    if (!file) {
      return json({ error: 'No file provided' }, 400);
    }

    const ALLOWED_EXTENSIONS = new Set(['jpg', 'jpeg', 'png', 'gif', 'webp', 'heic', 'heif']);
    const ALLOWED_MIME_TYPES = new Set(['image/jpeg', 'image/png', 'image/gif', 'image/webp', 'image/heic', 'image/heif']);

    const ext = file.name.split('.').pop().toLowerCase();
    if (!ALLOWED_EXTENSIONS.has(ext) || !ALLOWED_MIME_TYPES.has(file.type)) {
      return json({ error: 'Only photo files are allowed (JPEG, PNG, GIF, WebP, HEIC)' }, 415);
    }
    const id = `${Date.now()}-${crypto.randomUUID()}`;
    const fileKey = `photos/${id}.${ext}`;

    await env.BUCKET.put(fileKey, file.stream(), {
      httpMetadata: { contentType: file.type }
    });

    await env.DB.prepare(
      'INSERT INTO photos (file_key, uploader_name, location, guest_id) VALUES (?, ?, ?, ?)'
    ).bind(fileKey, uploaderName, location, guestId).run();

    // Warms both derivatives so the first gallery visitor doesn't wait on a
    // transform. The /v/ route regenerates on demand if this never lands.
    //
    // One message per variant, not one per photo: two transforms in a single
    // invocation exceeded the CPU limit and the second was killed every time.
    ctx?.waitUntil(
      env.PHOTO_QUEUE.sendBatch(
        Object.keys(VARIANTS).map(variant => ({
          body: { fileKey, variant, contentType: file.type }
        }))
      ).catch(err => console.error('queue send failed', fileKey, err))
    );

    return json({ success: true, fileKey });

  } catch (err) {
    return json({ error: err.message }, 500);
  }
}

// R2 list() intermittently fails with "internal error (10001)" even when the
// identical call succeeds a moment later. Callers page through the whole
// bucket, so a single failed page used to sink the entire request.
async function listWithRetry(env, opts, attempts = 4) {
  for (let i = 1; ; i++) {
    try {
      return await env.BUCKET.list(opts);
    } catch (err) {
      if (i >= attempts) throw err;
      await new Promise(resolve => setTimeout(resolve, 100 * 2 ** i));
    }
  }
}

/** Returns aggregate storage stats (bytes, photo count, estimated R2 cost) for the bucket. */
async function handleStorage(request, env) {
  try {
    let totalBytes = 0;
    let derivedBytes = 0;
    let photoCount = 0;
    let derivedCount = 0;

    // R2 list() returns at most 1000 objects per call. Three objects per photo
    // now (original + two derivatives), so paginate or the stats go badly stale.
    let cursor;
    do {
      const opts = { limit: 1000 };
      if (cursor) opts.cursor = cursor;
      const listed = await listWithRetry(env, opts);

      for (const obj of listed.objects) {
        totalBytes += obj.size;
        if (obj.key.startsWith('photos/')) photoCount++;
        if (obj.key.startsWith('derived/')) {
          derivedCount++;
          derivedBytes += obj.size;
        }
      }

      cursor = listed.truncated ? listed.cursor : undefined;
    } while (cursor);

    const mb = (totalBytes / (1024 * 1024)).toFixed(1);
    const gb = (totalBytes / (1024 * 1024 * 1024)).toFixed(3);
    const estimatedCost = (totalBytes / (1024 * 1024 * 1024) * 0.015).toFixed(4);

    return json({
      total_bytes: totalBytes,
      total_mb: parseFloat(mb),
      total_gb: parseFloat(gb),
      photo_count: photoCount,
      derived_count: derivedCount,
      derived_mb: parseFloat((derivedBytes / (1024 * 1024)).toFixed(1)),
      estimated_cost_usd: parseFloat(estimatedCost)
    });

  } catch (err) {
    return json({ error: err.message }, 500);
  }
}

/**
 * Reports which photos are missing derivatives, and optionally rebuilds them.
 *
 * GET  /derivatives        — audit only, changes nothing
 * POST /derivatives        — audit, then rebuild what is missing
 *
 * Because originals are kept, any derivative can be rebuilt at any time; this
 * is the sweep that makes that guarantee usable rather than theoretical. A
 * queue job that fails all its retries, or a photo uploaded while the Images
 * binding was unavailable, shows up here instead of waiting for a guest to
 * stumble onto the slow inline path.
 *
 * Rebuilding is capped per request: each variant costs an R2 get, a transform
 * and an R2 put, and Workers limit subrequests per invocation. Re-POST with the
 * `next_offset` from the previous response until `remaining` reaches zero.
 *
 * The offset exists because permanently unsupported sources never leave the
 * missing list — they cannot be built and will report missing forever. Without
 * a cursor, eight of them at the head would be retried on every call and the
 * sweep would never reach anything behind them. Only entries that were *not*
 * rebuilt advance it: a rebuilt derivative drops out of the next audit on its
 * own, so the list shifts under the cursor by exactly that many.
 */
const BACKFILL_LIMIT = 8;

// The scheduled sweep runs unattended, so it is deliberately smaller than a
// hand-driven backfill: it only has to keep pace with the trickle the queue
// misses, and a modest cap keeps each run well inside the invocation budget.
const SWEEP_LIMIT = 6;

// Bounds the work when the head of the list is all unsupported sources. They
// cost an R2 get each and no transform, but without a ceiling a bucket full of
// them would walk the entire list on every run.
const SWEEP_MAX_EXAMINED = 40;

/** Lists every (photo, variant) pair that has no stored derivative. */
async function findMissingDerivatives(env) {
  const { results } = await env.DB.prepare('SELECT file_key FROM photos ORDER BY id DESC').all();

  // One listing of derived/ beats two HEAD requests per photo: the sweep is
  // over every photo ever uploaded, and R2 charges per operation.
  const present = new Set();
  let cursor;
  do {
    const opts = { prefix: 'derived/', limit: 1000 };
    if (cursor) opts.cursor = cursor;
    const listed = await listWithRetry(env, opts);
    for (const obj of listed.objects) present.add(obj.key);
    cursor = listed.truncated ? listed.cursor : undefined;
  } while (cursor);

  const missing = [];
  for (const { file_key } of results) {
    for (const variant of Object.keys(VARIANTS)) {
      if (!present.has(derivedKey(file_key, variant))) {
        missing.push({ file_key, variant });
      }
    }
  }
  return { photoCount: results.length, missing };
}

/**
 * Rebuilds derivatives until `limit` transforms have been attempted.
 *
 * Unsupported sources do not count against the limit — they return before the
 * Images binding is touched, so they cost an R2 get and nothing else. Letting
 * them consume the budget would mean a handful of oversized photos at the head
 * of the list starving every real gap behind them. `maxExamined` still bounds
 * the walk so a bucket full of them cannot run away.
 */
async function rebuildBatch(env, entries, limit, maxExamined) {
  const rebuilt = [];
  const unsupported = [];
  const failed = [];
  let examined = 0;

  for (const { file_key, variant } of entries) {
    if (rebuilt.length + failed.length >= limit) break;
    if (++examined > maxExamined) break;

    const result = await generateVariant(env, file_key, variant);
    if (result.ok) rebuilt.push({ file_key, variant });
    else if (result.retryable) failed.push({ file_key, variant });
    else unsupported.push({ file_key, variant });
  }

  return { rebuilt, unsupported, failed };
}

async function handleDerivatives(request, env) {
  try {
    const rebuild = request.method === 'POST';
    const { photoCount, missing } = await findMissingDerivatives(env);

    if (!rebuild) {
      return json({
        photo_count: photoCount,
        missing_count: missing.length,
        missing: missing.slice(0, 100)
      });
    }

    const offset = Math.max(0, parseInt(new URL(request.url).searchParams.get('offset') || '0', 10) || 0);
    const { rebuilt, unsupported, failed } = await rebuildBatch(
      env, missing.slice(offset), BACKFILL_LIMIT, SWEEP_MAX_EXAMINED
    );

    // Anything not rebuilt stays in the next audit, so step over it. Rebuilt
    // entries leave the list and the cursor holds its place without moving.
    const nextOffset = offset + unsupported.length + failed.length;

    return json({
      photo_count: photoCount,
      missing_count: missing.length,
      offset,
      attempted: rebuilt.length + unsupported.length + failed.length,
      rebuilt_count: rebuilt.length,
      rebuilt,
      // Permanently untransformable — over the size cap or an undecodable
      // format. These serve the original via /v/ and will report missing forever.
      unsupported,
      failed,
      next_offset: nextOffset,
      remaining: Math.max(0, missing.length - nextOffset - rebuilt.length)
    });

  } catch (err) {
    return json({ error: err.message }, 500);
  }
}

/** Returns all photo records with their R2 file sizes, paginating through the bucket listing if needed. */
async function handlePresign(request, env) {
  try {
    const results = await env.DB.prepare(
      'SELECT * FROM photos ORDER BY id ASC'
    ).all();

    const photos = results.results.filter(p =>
      p.file_key.match(/\.(jpg|jpeg|png|gif|webp|heic)$/i)
    );

    // R2 list() returns at most 1000 objects per call; loop with cursor until
    // truncated is false to ensure every key's size is captured.
    // Sizes only steer ZIP batching, so a failed listing degrades to unknown
    // sizes (the client estimates) rather than failing the whole download.
    const sizeMap = new Map();
    try {
      let cursor;
      do {
        const opts = { prefix: 'photos/', limit: 1000 };
        if (cursor) opts.cursor = cursor;
        const listed = await listWithRetry(env, opts);
        for (const obj of listed.objects) sizeMap.set(obj.key, obj.size);
        cursor = listed.truncated ? listed.cursor : undefined;
      } while (cursor);
    } catch (err) {
      console.error('presign: R2 listing failed, returning photos without sizes:', err.message);
      sizeMap.clear();
    }

    return json({ photos: photos.map(p => ({
      id: p.id,
      file_key: p.file_key,
      uploader_name: p.uploader_name || 'Anonymous',
      location: p.location || 'Unknown',
      size: sizeMap.get(p.file_key) ?? 0,
      is_favorite: p.is_favorite || 0
    }))});

  } catch (err) {
    return json({ error: err.message }, 500);
  }
}

